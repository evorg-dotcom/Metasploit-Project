"""
report.py — Render a Markdown report from recon (and optional validation).
"""

from __future__ import annotations

from datetime import datetime, timezone


def build_report(
    scope,
    recon_result,
    advisor_text: str,
    validation_results: list | None = None,
) -> str:
    validation_results = validation_results or []
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")

    out: list[str] = []
    out.append("# LabScout Report")
    out.append("")
    out.append(f"- Generated: {now}")
    out.append(f"- Target (confirmed in scope): `{scope.resolved_ip}`")
    out.append(f"- Matched allowlist entry: `{scope.matched_allowlist}`")
    out.append(f"- Recon profile: `{recon_result.profile}`")
    out.append("")
    out.append("> Authorized lab use only. This report describes a scan of a "
               "single, operator-owned Metasploitable 3 VM on an isolated "
               "network.")
    out.append("")

    out.append("## Open services")
    out.append("")
    any_ports = False
    for host, ports in recon_result.parsed.items():
        open_ports = {p: i for p, i in ports.items()
                      if (i.get("state") or "") == "open"}
        if not open_ports:
            continue
        any_ports = True
        out.append(f"### {host}")
        out.append("")
        out.append("| Port | Service | Product | Version |")
        out.append("|------|---------|---------|---------|")
        for port, info in sorted(open_ports.items()):
            out.append(
                f"| {port}/tcp | {info.get('name') or ''} "
                f"| {info.get('product') or ''} | {info.get('version') or ''} |"
            )
        out.append("")
    if not any_ports:
        out.append("_No open ports were parsed._")
        out.append("")

    out.append("## Advisor interpretation")
    out.append("")
    out.append("```")
    out.append(advisor_text)
    out.append("```")
    out.append("")

    if validation_results:
        out.append("## Validation (optional, operator-confirmed)")
        out.append("")
        for v in validation_results:
            status = "ran" if v.ran else "aborted"
            out.append(f"### `{v.module}` ({status})")
            out.append("")
            out.append("```")
            out.append(v.output.strip() or "(no output)")
            out.append("```")
            out.append("")

    out.append("## Scope and safety notes")
    out.append("")
    out.append("- Target was validated as a private address and matched the "
               "configured lab allowlist before any action.")
    out.append("- Recon used a fixed Nmap profile; no shell commands were "
               "generated by a model.")
    out.append("- Any validation step above was limited to an allowlisted "
               "module, re-pinned to the confirmed target, and required "
               "explicit confirmation.")
    out.append("")
    return "\n".join(out)
